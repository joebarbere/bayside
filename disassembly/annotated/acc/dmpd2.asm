; BINARY STRUCTURE
; ========================================================================
;
; MZ + DM89 header (512 bytes)
; File size: 6,685 bytes
; Load image: 6,173 bytes (after header)
; DM89 entry point: 0109:0002 (MSC 5.x CRT startup)
; SS:SP = 0196:0FA0
;
; Segment Map (5 segments, 13 relocations):
;   seg_0000     CODE     Printer driver 2 code + DMGUF thunks
;   seg_0109     CODE     MSC 5.x CRT startup
;   seg_0113     CODE     DM89 import far-call dispatcher
;   seg_0117     DATA     DGROUP -- printer config, escape sequences, strings
;   seg_0196     STACK    Stack segment
;
; Medium memory model: multiple code segments, DGROUP at 0117.
;
; DM flags: 0x0000
; Imports: dmguf
;
; ========================================================================
; INTERRUPT SERVICES USED
; ========================================================================
;
; INT E0h (DeskMate API):
;   AH=00h (Core services)
;   AH=02h (Resource/UI services)
;   AH=06h (Window/event services)
;   AH=07h (Memory services)
;
; INT 21h (DOS API):
;   AH=25h (Set interrupt vector)
;   AH=30h (Get DOS version)
;   AH=35h (Get interrupt vector)
;   AH=3Eh (Close file)
;   AH=40h (Write file)
;   AH=44h (IOCTL)
;   AH=4Ah (Resize memory block)
;   AH=4Ch (Exit process)
;
; Other interrupts:
;   INT 20h x1 (DOS terminate)
;   INT ABh x1 (Printer I/O)
;
