#!/usr/bin/env python3
"""
mkprotos.py -- Generate declarations for every original function that C may
call and that is not (yet) implemented in C.

Declarations are old-style (`int name();`): original code is MSC 5.x cdecl,
arguments are promoted words, and the deep trace (pdm_trace.py --deep)
checks the actual argument values, so per-call type checking adds little
while typed prototypes would have to be hand-maintained for ~200 functions.
Functions implemented in C are declared with full prototypes in the area
headers (src/hangman/*.h), and are skipped here, as are functions any
header already declares.

Usage: tools/mkprotos.py functions.txt SRC_DIR -o protos.h
"""
import argparse
import re
from pathlib import Path

# Hand-written helpers with register calling conventions: not callable from C.
NOT_CDECL = {"hangman_itoaBuf", "hangman_strcpyDI", "hangman_strlenSI",
             "dm_videoNameIndex"}


def c_functions(src):
    """name -> address for every C function carrying an address comment."""
    out = {}
    for f in sorted(Path(src).glob("*.c")):
        text = f.read_text()
        for m in re.finditer(r"/\*\s*address:\s*0000:([0-9A-Fa-f]{4})\b(.*?)\*/\s*"
                             r"(?:[\w\s\*]+?)\b(\w+)\s*\(", text, re.S):
            out[m.group(3)] = int(m.group(1), 16)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("functions")
    ap.add_argument("src")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--list-c", metavar="FILE",
                    help="also write the C-implemented functions as "
                         "'ADDR name' lines (for pdm_trace.py --deep-skip)")
    a = ap.parse_args()
    funcs = []
    for line in open(a.functions):
        line = line.split("#")[0].strip()
        if line:
            addr, name = line.split()[:2]
            funcs.append((int(addr, 16), name))
    in_c = c_functions(a.src)
    if a.list_c:
        Path(a.list_c).write_text("".join(f"{v:04X} {k}\n"
                                          for k, v in sorted(in_c.items(), key=lambda x: x[1])))
    declared = set()
    for h in Path(a.src).glob("*.h"):
        declared |= set(re.findall(r"\b(\w+)\s*\(", h.read_text()))
    lines = ["/* GENERATED by tools/mkprotos.py -- original functions not yet in C.",
             " * Old-style declarations on purpose (see the tool's docstring). */",
             "#ifndef PROTOS_H", "#define PROTOS_H"]
    for addr, name in funcs:
        if name in in_c or name in declared or name in NOT_CDECL:
            continue
        lines.append(f"int {name}();{' ' * max(1, 32 - len(name))}/* {addr:04X} */")
    lines.append("#endif")
    Path(a.out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
